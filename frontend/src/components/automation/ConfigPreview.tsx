import { Button } from "@/components/ui/Button";

interface ConfigPreviewProps {
  config?: string;
  lineCount?: number;
  error?: Error;
  loading: boolean;
  onCopy: () => void;
}

export function ConfigPreview({ config, lineCount, error, loading, onCopy }: ConfigPreviewProps) {
  return (
    <section className="overflow-hidden rounded-xl bg-slate-950 shadow-sm">
      <div className="flex items-center justify-between border-b border-white/10 px-5 py-4">
        <div>
          <h2 className="text-sm font-medium text-white">Generated IOS configuration</h2>
          <p className="mt-1 text-xs text-slate-500">
            {error ? "Validation failed" : loading ? "Generating…" : `Generated by the API · ${lineCount ?? 0} lines`}
          </p>
        </div>
        <Button variant="glass" size="sm" disabled={!config} onClick={onCopy}>Copy CLI</Button>
      </div>
      {error ? (
        <div className="p-5 font-mono text-xs leading-6 text-rose-300">{error.message}</div>
      ) : (
        <pre className="overflow-x-auto p-5 font-mono text-xs leading-6 text-cyan-100">{config ?? ""}</pre>
      )}
    </section>
  );
}
